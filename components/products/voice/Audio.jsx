'use client';

import { useEffect, useRef, useState } from 'react';
import { Pause, Play } from 'lucide-react';
import { CALL, SAMPLES, VOICES } from '@/lib/voice';

// One sound at a time on the page: starting one pauses the rest.
const solo = (el) => document.querySelectorAll('audio').forEach((a) => a !== el && a.pause());
const BARS = [5, 9, 14, 8, 12, 16, 7, 11, 6, 10, 15, 9, 13, 7];

function Bars({ on, className = '' }) {
  return (
    <span aria-hidden="true" className={`flex h-4 items-center gap-[3px] transition-opacity duration-300 ${on ? 'opacity-100' : 'opacity-0'} ${className}`}>
      {BARS.map((h, i) => <span key={i} className={`w-[2px] rounded-full bg-current ${on ? 'mock-bar' : ''}`} style={{ height: h, '--i': i }} />)}
    </span>
  );
}

function PlayButton({ on, label, onClick, dark }) {
  return (
    <button type="button" onClick={onClick} aria-label={`${on ? 'Pause' : 'Play'} ${label}`}
      className={`inline-flex h-11 w-11 shrink-0 items-center justify-center rounded-full transition duration-150 ease-in-out hover:brightness-90 ${dark ? 'bg-white text-aubergine' : 'bg-ink text-white'}`}>
      {on ? <Pause size={16} fill="currentColor" /> : <Play size={16} fill="currentColor" className="translate-x-px" />}
    </button>
  );
}

// The whole call, line by line: the line being spoken is full ink, the rest wait. The progress rail is one CSS
// fill for the call's length, paused with the audio, so it never steps.
export function Call() {
  const audio = useRef(null);
  const [on, setOn] = useState(false);
  const [t, setT] = useState(-1);
  const [run, setRun] = useState(0);
  const now = t < 0 ? -1 : CALL.lines.findLastIndex((l) => l.start <= t + 0.05);
  const toggle = () => {
    const a = audio.current;
    if (!a.paused) return a.pause();
    if (a.ended || a.currentTime === 0) setRun((r) => r + 1);
    solo(a);
    a.play().catch(() => {});
  };
  return (
    <div className="mx-auto max-w-[880px] overflow-hidden rounded-2xl bg-night text-left text-white">
      <div className="flex items-center gap-4 border-b border-white/10 px-5 py-4 md:px-8">
        <PlayButton on={on} label="the call" onClick={toggle} dark />
        <div className="min-w-0 flex-1">
          <p className="m-0 text-[15px] font-medium">A support call, both sides Amami</p>
          <span className="mt-2 block h-[2px] overflow-hidden rounded-full bg-white/10">
            {run > 0 && <span key={run} className="fill-run block h-full bg-sun" style={{ '--dur': `${CALL.duration}s`, animationIterationCount: 1, animationFillMode: 'both', animationPlayState: on ? 'running' : 'paused' }} />}
          </span>
        </div>
        <Bars on={on} className="hidden text-sun sm:flex" />
      </div>
      <ol className="m-0 list-none px-5 py-4 md:px-8 md:py-6">
        {CALL.lines.map((l, i) => {
          const state = now < 0 ? 'idle' : i === now ? 'now' : i < now ? 'past' : 'next';
          return (
            <li key={i} className={`grid grid-cols-[64px_1fr] gap-x-4 py-2.5 transition-opacity duration-300 md:grid-cols-[80px_1fr] ${state === 'next' ? 'opacity-40' : state === 'past' ? 'opacity-60' : 'opacity-100'}`}>
              <span className={`pt-0.5 text-[12px] ${l.role === 'Agent' ? 'text-sun' : 'text-white/50'}`}>{l.role === 'Agent' ? 'Agent' : 'Caller'}</span>
              <span>
                <span lang="ro" className="block text-[15px] leading-[1.5]">{l.text}</span>
                <span className="mt-0.5 block text-[13px] leading-[1.5] text-white/50">{l.en}</span>
              </span>
            </li>
          );
        })}
      </ol>
      <p className="m-0 border-t border-white/10 px-5 py-3 text-[12px] text-white/45 md:px-8">A scripted call, not a customer's. Seven lines in two voices, each generated by Amami on a CPU.</p>
      <audio ref={audio} src={CALL.src} preload="none" onPlay={() => setOn(true)} onPause={() => setOn(false)} onEnded={() => { setOn(false); setT(-1); }}
        onTimeUpdate={(e) => setT(e.currentTime)} />
    </div>
  );
}

// The voices: the same six lines in each, one row per kind of thing a voice agent says.
export function Voices() {
  const audio = useRef(null);
  const [voice, setVoice] = useState(VOICES[0].key);
  const [playing, setPlaying] = useState(null);
  useEffect(() => { audio.current?.pause(); }, [voice]);
  const play = (s) => {
    const a = audio.current;
    if (playing === s.slug && !a.paused) return a.pause();
    a.src = s.src(voice);
    solo(a);
    a.play().then(() => setPlaying(s.slug)).catch(() => {});
  };
  return (
    <div>
      <div role="tablist" aria-label="Voice" className="flex w-fit rounded-full bg-stone p-1">
        {VOICES.map((v) => (
          <button key={v.key} type="button" role="tab" aria-selected={v.key === voice} onClick={() => setVoice(v.key)}
            className={`h-9 rounded-full px-4 text-[14px] font-medium transition-colors duration-150 ease-in-out ${v.key === voice ? 'bg-white text-ink shadow-[0_0_0_1px_rgba(10,10,10,.06)]' : 'text-ink/60 hover:text-ink'}`}>{v.name}</button>
        ))}
      </div>
      <ul className="m-0 mt-6 list-none border-b border-hairline p-0">
        {SAMPLES.map((s) => {
          const on = playing === s.slug;
          return (
            <li key={s.slug} className="flex items-center gap-4 border-t border-hairline py-4">
              <PlayButton on={on} label={`${s.category}, ${VOICES.find((v) => v.key === voice).name}`} onClick={() => play(s)} />
              <div className="min-w-0 flex-1">
                <p className="m-0 text-[12px] text-ink/50">{s.category}</p>
                <p lang="ro" className="m-0 mt-0.5 text-[15px] leading-[1.5]">{s.text}</p>
              </div>
              <Bars on={on} className="hidden text-ink/60 sm:flex" />
            </li>
          );
        })}
      </ul>
      <audio ref={audio} preload="none" onPause={() => setPlaying(null)} onEnded={() => setPlaying(null)} />
    </div>
  );
}
